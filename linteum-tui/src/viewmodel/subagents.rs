//! Subagent task view: parent-side status plus the child's derived context.
//!
//! The parent gateway emits `subagent.requested/started/progress/result/error`
//! on the parent session.  The child's actual messages are *not* forwarded
//! into the parent transcript (context isolation); the TUI fetches them on
//! demand with the read-only `session.context` command.

use serde_json::Value;

use crate::protocol::{ErrorInfo, Frame};

use super::state::UsageView;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum SubagentStatus {
    #[default]
    Requested,
    Running,
    Completed,
    Failed,
    Cancelled,
    Timeout,
}

impl SubagentStatus {
    pub fn label(self) -> &'static str {
        match self {
            Self::Requested => "requested",
            Self::Running => "running",
            Self::Completed => "completed",
            Self::Failed => "failed",
            Self::Cancelled => "cancelled",
            Self::Timeout => "timeout",
        }
    }

    pub fn is_terminal(self) -> bool {
        !matches!(self, Self::Requested | Self::Running)
    }
}

#[derive(Debug, Clone, Default)]
pub struct SubagentView {
    pub call_id: String,
    pub child_session_id: Option<String>,
    /// Short goal label generated by the parent model for UI display.
    pub title: Option<String>,
    pub task: String,
    pub status: SubagentStatus,
    pub phase: Option<String>,
    pub round: u64,
    pub last_tool: Option<String>,
    pub message_count: u64,
    pub tokens_input: u64,
    pub tokens_output: u64,
    pub tools: Vec<String>,
    pub model_profile: Option<String>,
    pub read_only: bool,
    pub approval_policy: Option<String>,
    pub timeout_ms: Option<u64>,
    pub summary: Option<String>,
    pub summary_ref: Option<String>,
    pub summary_truncated: bool,
    pub error: Option<ErrorInfo>,
    pub code: Option<String>,
    pub usage: UsageView,
    pub rounds: u64,
    pub duration_ms: Option<u64>,
}

impl SubagentView {
    pub fn title_preview(&self, limit: usize) -> String {
        let title = self.title.as_deref().unwrap_or("").trim();
        let first = if title.is_empty() {
            self.task.lines().next().unwrap_or("").trim()
        } else {
            title
        };
        let text = if first.is_empty() {
            "(no task text)"
        } else {
            first
        };
        let count = text.chars().count();
        if count <= limit {
            text.to_owned()
        } else {
            text.chars()
                .take(limit.saturating_sub(1))
                .collect::<String>()
                + "…"
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct ContextMessage {
    pub role: String,
    pub text: String,
}

#[derive(Debug, Clone, Default)]
pub struct SubagentContextView {
    pub session_id: String,
    pub kind: String,
    pub phase: Option<String>,
    pub round: u64,
    pub source: String,
    pub system_blocks_included: bool,
    pub digest: String,
    pub estimated_tokens: u64,
    pub tools: Vec<String>,
    pub messages: Vec<ContextMessage>,
}

impl SubagentContextView {
    fn from_value(value: &Value) -> Result<Self, String> {
        let session_id = value
            .get("session_id")
            .and_then(Value::as_str)
            .ok_or_else(|| "context response is missing session_id".to_owned())?;
        let mut view = Self {
            session_id: session_id.to_owned(),
            kind: string_field(value, "kind").unwrap_or_else(|| "unknown".to_owned()),
            phase: string_field(value, "phase"),
            round: value.get("round").and_then(Value::as_u64).unwrap_or(0),
            source: string_field(value, "source").unwrap_or_else(|| "unknown".to_owned()),
            system_blocks_included: value
                .get("system_blocks_included")
                .and_then(Value::as_bool)
                .unwrap_or(false),
            digest: string_field(value, "digest").unwrap_or_default(),
            estimated_tokens: value
                .get("estimated_tokens")
                .and_then(Value::as_u64)
                .unwrap_or(0),
            tools: string_list(value.get("tools")),
            messages: Vec::new(),
        };
        for message in value
            .get("messages")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            view.messages.push(ContextMessage {
                role: string_field(message, "role").unwrap_or_else(|| "unknown".to_owned()),
                text: message_text(message),
            });
        }
        Ok(view)
    }
}

#[derive(Debug, Clone, Default)]
pub struct SubagentsState {
    pub entries: Vec<SubagentView>,
    pub selected: usize,
    pub detail: Option<SubagentContextView>,
    /// Child session id whose `session.context` request is in flight.
    pub loading: Option<String>,
    pub error: Option<String>,
    pub scroll: usize,
}

impl SubagentsState {
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn running_count(&self) -> usize {
        self.entries
            .iter()
            .filter(|entry| entry.status == SubagentStatus::Running)
            .count()
    }

    pub fn selected_entry(&self) -> Option<&SubagentView> {
        self.entries.get(self.selected)
    }

    pub fn select_next(&mut self) {
        if !self.entries.is_empty() {
            self.selected = (self.selected + 1).min(self.entries.len() - 1);
        }
    }

    pub fn select_previous(&mut self) {
        self.selected = self.selected.saturating_sub(1);
    }

    fn entry_mut(&mut self, call_id: &str) -> &mut SubagentView {
        if let Some(index) = self
            .entries
            .iter()
            .position(|entry| entry.call_id == call_id)
        {
            return &mut self.entries[index];
        }
        self.entries.push(SubagentView {
            call_id: call_id.to_owned(),
            ..Default::default()
        });
        self.entries
            .last_mut()
            .expect("entry pushed immediately above")
    }

    pub fn apply_frame(&mut self, frame: &Frame) {
        let Some(call_id) = frame.payload.get("call_id").and_then(Value::as_str) else {
            return;
        };
        if call_id.is_empty() {
            return;
        }
        match frame.frame.as_str() {
            "subagent.requested" => {
                let entry = self.entry_mut(call_id);
                apply_title(entry, &frame.payload);
                entry.task = string_field(&frame.payload, "task").unwrap_or_default();
                entry.tools = string_list(frame.payload.get("tools"));
                entry.model_profile = string_field(&frame.payload, "model_profile");
                if !entry.status.is_terminal() {
                    entry.status = SubagentStatus::Requested;
                }
            }
            "subagent.started" => {
                let entry = self.entry_mut(call_id);
                if entry.status.is_terminal() {
                    return; // a late start must not downgrade a terminal view
                }
                apply_title(entry, &frame.payload);
                entry.child_session_id = string_field(&frame.payload, "child_session_id");
                entry.tools = string_list(frame.payload.get("tools"));
                entry.model_profile = string_field(&frame.payload, "model_profile");
                entry.read_only = frame
                    .payload
                    .get("read_only")
                    .and_then(Value::as_bool)
                    .unwrap_or(false);
                entry.approval_policy = string_field(&frame.payload, "approval_policy");
                entry.timeout_ms = frame.payload.get("timeout_ms").and_then(Value::as_u64);
                entry.status = SubagentStatus::Running;
            }
            "subagent.progress" => {
                let entry = self.entry_mut(call_id);
                if entry.status.is_terminal() {
                    return;
                }
                apply_title(entry, &frame.payload);
                entry.status = SubagentStatus::Running;
                entry.phase = string_field(&frame.payload, "phase");
                entry.round = frame
                    .payload
                    .get("round")
                    .and_then(Value::as_u64)
                    .unwrap_or(0);
                entry.last_tool = string_field(&frame.payload, "last_tool");
                entry.message_count = frame
                    .payload
                    .get("message_count")
                    .and_then(Value::as_u64)
                    .unwrap_or(0);
                entry.tokens_input = frame
                    .payload
                    .get("tokens_input")
                    .and_then(Value::as_u64)
                    .unwrap_or(0);
                entry.tokens_output = frame
                    .payload
                    .get("tokens_output")
                    .and_then(Value::as_u64)
                    .unwrap_or(0);
            }
            "subagent.result" => {
                let entry = self.entry_mut(call_id);
                if terminal_locked(entry.status) {
                    return;
                }
                apply_title(entry, &frame.payload);
                entry.status = SubagentStatus::Completed;
                if let Some(child_id) = string_field(&frame.payload, "child_session_id") {
                    entry.child_session_id = Some(child_id);
                }
                entry.summary = string_field(&frame.payload, "summary");
                entry.summary_ref = string_field(&frame.payload, "summary_ref");
                entry.summary_truncated = frame
                    .payload
                    .get("summary_truncated")
                    .and_then(Value::as_bool)
                    .unwrap_or(false);
                entry.usage = usage_field(&frame.payload);
                entry.rounds = frame
                    .payload
                    .get("rounds")
                    .and_then(Value::as_u64)
                    .unwrap_or(0);
                entry.duration_ms = frame.payload.get("duration_ms").and_then(Value::as_u64);
                entry.phase = Some("idle".to_owned());
            }
            "subagent.error" => {
                let entry = self.entry_mut(call_id);
                if terminal_locked(entry.status) {
                    return;
                }
                apply_title(entry, &frame.payload);
                entry.status = status_from_failure(&frame.payload);
                if let Some(child_id) = string_field(&frame.payload, "child_session_id") {
                    entry.child_session_id = Some(child_id);
                }
                entry.code = string_field(&frame.payload, "code");
                entry.error = frame
                    .payload
                    .get("error_info")
                    .and_then(|value| serde_json::from_value(value.clone()).ok());
                entry.usage = usage_field(&frame.payload);
                entry.rounds = frame
                    .payload
                    .get("rounds")
                    .and_then(Value::as_u64)
                    .unwrap_or(0);
                entry.duration_ms = frame.payload.get("duration_ms").and_then(Value::as_u64);
            }
            _ => {}
        }
    }

    pub fn apply_cancel(&mut self, payload: &Value) {
        for call_id in string_list(payload.get("call_ids")) {
            if let Some(entry) = self
                .entries
                .iter_mut()
                .find(|entry| entry.call_id == call_id)
                && !entry.status.is_terminal()
            {
                entry.status = SubagentStatus::Cancelled;
            }
        }
    }

    pub fn apply_context_result(&mut self, value: &Value) {
        self.loading = None;
        match SubagentContextView::from_value(value) {
            Ok(view) => {
                self.detail = Some(view);
                self.error = None;
                self.scroll = 0;
            }
            Err(error) => self.error = Some(error),
        }
    }
}

fn apply_title(entry: &mut SubagentView, payload: &Value) {
    if let Some(title) = payload.get("title").and_then(Value::as_str) {
        let title = title.trim();
        if !title.is_empty() {
            entry.title = Some(title.to_owned());
        }
    }
}

fn terminal_locked(status: SubagentStatus) -> bool {
    // A cancellation *notice* may still be upgraded by the authoritative
    // `subagent.error`; a real terminal event must not be replaced.
    matches!(
        status,
        SubagentStatus::Completed | SubagentStatus::Failed | SubagentStatus::Timeout
    )
}

fn status_from_failure(payload: &Value) -> SubagentStatus {
    match string_field(payload, "code").as_deref() {
        Some("E_SUBAGENT_CANCELLED") => SubagentStatus::Cancelled,
        Some("E_SUBAGENT_TIMEOUT") => SubagentStatus::Timeout,
        _ if string_field(payload, "finish").as_deref() == Some("cancelled") => {
            SubagentStatus::Cancelled
        }
        _ if string_field(payload, "finish").as_deref() == Some("timeout") => {
            SubagentStatus::Timeout
        }
        _ => SubagentStatus::Failed,
    }
}

fn usage_field(payload: &Value) -> UsageView {
    let Some(usage) = payload.get("usage") else {
        return UsageView::default();
    };
    UsageView {
        input_tokens: usage
            .get("input_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0),
        output_tokens: usage
            .get("output_tokens")
            .and_then(Value::as_u64)
            .unwrap_or(0),
        cache_read: usage.get("cache_read").and_then(Value::as_u64).unwrap_or(0),
        cache_write: usage
            .get("cache_write")
            .and_then(Value::as_u64)
            .unwrap_or(0),
        usd: usage.get("usd").and_then(Value::as_f64).unwrap_or(0.0),
    }
}

fn message_text(message: &Value) -> String {
    let mut text = content_text(message.get("content"));
    if let Some(reasoning) = message.get("reasoning").and_then(Value::as_str)
        && !reasoning.is_empty()
    {
        text.push_str("\n[reasoning] ");
        text.push_str(reasoning);
    }
    if let Some(calls) = message.get("tool_calls").and_then(Value::as_array) {
        for call in calls {
            let name = call
                .get("name")
                .or_else(|| {
                    call.get("function")
                        .and_then(|function| function.get("name"))
                })
                .and_then(Value::as_str)
                .unwrap_or("tool");
            let args = call
                .get("args")
                .or_else(|| call.get("arguments"))
                .or_else(|| {
                    call.get("function")
                        .and_then(|function| function.get("arguments"))
                })
                .map(|value| value.to_string())
                .unwrap_or_default();
            if !text.is_empty() {
                text.push('\n');
            }
            text.push_str(&format!("[tool_call] {name} {args}"));
        }
    }
    if let Some(call_id) = message.get("tool_call_id").and_then(Value::as_str) {
        text = format!("[tool_result {call_id}]\n{text}");
    }
    text
}

fn content_text(content: Option<&Value>) -> String {
    match content {
        Some(Value::String(text)) => text.clone(),
        Some(Value::Array(parts)) => parts
            .iter()
            .filter_map(|part| {
                (part.get("type").and_then(Value::as_str) == Some("text"))
                    .then(|| part.get("text").and_then(Value::as_str))
                    .flatten()
            })
            .collect::<Vec<_>>()
            .join(""),
        Some(Value::Null) | None => String::new(),
        Some(other) => other.to_string(),
    }
}

fn string_field(value: &Value, key: &str) -> Option<String> {
    value.get(key).and_then(Value::as_str).map(str::to_owned)
}

fn string_list(value: Option<&Value>) -> Vec<String> {
    value
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn frame(name: &str, payload: Value) -> Frame {
        Frame {
            v: 1,
            id: "f".into(),
            frame: name.into(),
            payload,
            session_id: Some("parent".into()),
            seq: Some(1),
            ephemeral: false,
            replay: false,
            ordinal: 0,
        }
    }

    #[test]
    fn progress_updates_a_running_entry() {
        let mut state = SubagentsState::default();
        state.apply_frame(&frame(
            "subagent.requested",
            serde_json::json!({"call_id": "c1", "task": "review"}),
        ));
        state.apply_frame(&frame(
            "subagent.started",
            serde_json::json!({"call_id": "c1", "child_session_id": "child"}),
        ));
        state.apply_frame(&frame(
            "subagent.progress",
            serde_json::json!({
                "call_id": "c1", "phase": "acting", "round": 2,
                "last_tool": "read_file", "tokens_input": 10, "tokens_output": 4,
            }),
        ));
        let entry = &state.entries[0];
        assert_eq!(entry.status, SubagentStatus::Running);
        assert_eq!(entry.phase.as_deref(), Some("acting"));
        assert_eq!(entry.last_tool.as_deref(), Some("read_file"));
        assert_eq!(entry.tokens_input, 10);
    }

    #[test]
    fn terminal_status_wins_over_late_progress() {
        let mut state = SubagentsState::default();
        state.apply_frame(&frame(
            "subagent.result",
            serde_json::json!({"call_id": "c1", "summary": "done"}),
        ));
        state.apply_frame(&frame(
            "subagent.progress",
            serde_json::json!({"call_id": "c1", "phase": "acting"}),
        ));
        assert_eq!(state.entries[0].status, SubagentStatus::Completed);
    }
}
